"""Run simulations in parallel inside the current allocation (one Slurm job, many cores).

Every run directory gets a ``run.sh`` that leaves a marker: ``DONE`` on exit code 0,
``FAILED`` (with the reason) otherwise. Runs that already have ``DONE`` are not repeated,
so after an interruption only the unfinished runs execute again.
"""
from __future__ import annotations

import logging
import os
import signal
import subprocess
import time
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
from pathlib import Path
from typing import Sequence

log = logging.getLogger(__name__)

RUN_SCRIPT = """#!/bin/bash
# generated by pnm_al - runs one simulation and leaves a DONE / FAILED marker
cd "$(dirname "${{BASH_SOURCE[0]}}")" || exit 99
rm -f DONE FAILED
{command}
rc=$?
if [ "$rc" -eq 0 ]; then touch DONE; else echo "exit code $rc" > FAILED; fi
exit "$rc"
"""


@dataclass
class RunResult:
    status: str            # "done" | "failed"
    runtime_s: float | None
    message: str = ""


def write_run_script(run_dir: Path, command: str) -> Path:
    script = run_dir / "run.sh"
    script.write_text(RUN_SCRIPT.format(command=command))
    script.chmod(0o755)
    return script


def outcome(run_dir: Path) -> RunResult | None:
    if (run_dir / "DONE").exists():
        return RunResult("done", None, "already finished")
    if (run_dir / "FAILED").exists():
        return RunResult("failed", None, (run_dir / "FAILED").read_text().strip())
    return None


def default_workers() -> int:
    for var in ("SLURM_CPUS_PER_TASK", "SLURM_NTASKS"):
        if os.environ.get(var, "").isdigit():
            return max(1, int(os.environ[var]))
    return max(1, os.cpu_count() or 1)


def _run_one(run_dir: Path, timeout: float | None) -> RunResult:
    start = time.monotonic()
    proc = subprocess.Popen(["bash", str(run_dir / "run.sh")], stdout=subprocess.DEVNULL,
                            stderr=subprocess.DEVNULL, start_new_session=True)
    try:
        proc.wait(timeout=timeout)
    except subprocess.TimeoutExpired:
        os.killpg(proc.pid, signal.SIGKILL)          # kill bash *and* the simulator it started
        proc.wait()
        (run_dir / "FAILED").write_text(f"timeout after {timeout:.0f} s\n")
        return RunResult("failed", time.monotonic() - start, f"timeout after {timeout:.0f} s")
    runtime = time.monotonic() - start
    result = outcome(run_dir)
    if result is None:                               # killed before run.sh could write a marker
        return RunResult("failed", runtime, f"no DONE/FAILED marker (exit code {proc.returncode})")
    return RunResult(result.status, runtime, "" if result.status == "done" else result.message)


def execute(run_dirs: Sequence[Path], command: str | None, workers: int,
            timeout: float | None = None) -> dict[Path, RunResult]:
    """Run every run dir that has no DONE marker yet; return a result per run dir."""
    results: dict[Path, RunResult] = {}
    todo = []
    for run_dir in run_dirs:
        if (run_dir / "DONE").exists():
            results[run_dir] = RunResult("done", None, "already finished")
        elif command is None:                        # lookup simulator: nothing to execute
            (run_dir / "DONE").touch()
            results[run_dir] = RunResult("done", 0.0)
        else:
            write_run_script(run_dir, command)
            todo.append(run_dir)
    if todo:
        log.info("running %d simulations on %d workers", len(todo), workers)
        with ThreadPoolExecutor(max_workers=max(1, workers)) as pool:
            for run_dir, result in zip(todo, pool.map(lambda d: _run_one(d, timeout), todo)):
                results[run_dir] = result
        n_failed = sum(results[d].status == "failed" for d in todo)
        log.info("%d simulations finished, %d failed", len(todo) - n_failed, n_failed)
    return results
